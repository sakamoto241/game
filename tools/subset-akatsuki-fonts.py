"""Build the bundled OFL fonts for akatsuki.html.

Usage: python3 -I tools/subset-akatsuki-fonts.py FONT_DIR
FONT_DIR holds ShipporiMinchoB1-Regular.ttf, ShipporiMinchoB1-Bold.ttf and Cinzel[wght].ttf
from https://github.com/google/fonts (ofl/shipporiminchob1, ofl/cinzel).

Writes into akatsuki-fonts/:
- akatsuki-mincho-{regular,bold}.woff2: every character the game text uses (always loaded).
- akatsuki-mincho-extra-{regular,bold}.woff2: the remaining JIS level-1 kanji. Their
  @font-face carries a unicode-range, so browsers download them only when such a
  character is actually on screen.
- akatsuki-cinzel.woff2, akatsuki-fonts.css (with content-hash cache busting) and
  glyphs.txt, which akatsuki-fonts.test.cjs checks the game text against.
Rebuild after text changes when the test reports characters that are not covered.
"""
import hashlib, pathlib, re, sys
from fontTools import subset

root = pathlib.Path(__file__).resolve().parent.parent
out = root / 'akatsuki-fonts'
sources = ['akatsuki.html', 'akatsuki.js', 'akatsuki-story.js', 'akatsuki-core.js']
text = ''.join((root / f).read_text(encoding='utf-8') for f in sources)

def codes(*ranges):
    return {chr(c) for a, b in ranges for c in range(a, b)}

base = codes((0x20, 0x7f), (0x3000, 0x3100), (0xff01, 0xff5f)) | set('・…―─‐〜→←↑↓◆◇●○＋·—–')
used = {c for c in text if ord(c) >= 0x20}
core = used | base
level1 = set()  # JIS X 0208 level-1 kanji (Shift_JIS lead bytes 0x88-0x98)
for lead in range(0x88, 0x99):
    for trail in [*range(0x40, 0x7f), *range(0x80, 0xfd)]:
        try:
            c = bytes([lead, trail]).decode('shift_jis')
        except UnicodeDecodeError:
            continue
        if 0x4e00 <= ord(c) <= 0x9fff:
            level1.add(c)
extra = level1 - core

def ranges(chars):
    cps = sorted(ord(c) for c in chars)
    spans, start = [], cps[0]
    for prev, cur in zip(cps, cps[1:] + [None]):
        if cur != prev + 1:
            spans.append(f'U+{start:X}' if start == prev else f'U+{start:X}-{prev:X}')
            start = cur
    return ','.join(spans)

def build(src, target, chars):
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['kern', 'liga', 'palt']
    options.name_IDs = ['*']
    font = subset.load_font(str(src), options)
    sub = subset.Subsetter(options)
    sub.populate(text=''.join(sorted(chars)))
    sub.subset(font)
    path = out / target
    subset.save_font(font, str(path), options)
    print(target, path.stat().st_size // 1024, 'KB')
    return hashlib.sha1(path.read_bytes()).hexdigest()[:8]

src = pathlib.Path(sys.argv[1])
latin = {c for c in core if ord(c) < 0x250} | set('·—–')
v = {
    'regular': build(src / 'ShipporiMinchoB1-Regular.ttf', 'akatsuki-mincho-regular.woff2', core),
    'bold': build(src / 'ShipporiMinchoB1-Bold.ttf', 'akatsuki-mincho-bold.woff2', core),
    'extra-regular': build(src / 'ShipporiMinchoB1-Regular.ttf', 'akatsuki-mincho-extra-regular.woff2', extra),
    'extra-bold': build(src / 'ShipporiMinchoB1-Bold.ttf', 'akatsuki-mincho-extra-bold.woff2', extra),
    'cinzel': build(src / 'Cinzel[wght].ttf', 'akatsuki-cinzel.woff2', latin),
}
extra_range = ranges(extra)
css = f"""/* Generated by tools/subset-akatsuki-fonts.py. Shippori Mincho B1 and Cinzel, SIL OFL 1.1. */
@font-face{{font-family:'Akatsuki Mincho';src:url('akatsuki-mincho-regular.woff2?v={v['regular']}') format('woff2');font-weight:400 500;font-display:swap}}
@font-face{{font-family:'Akatsuki Mincho';src:url('akatsuki-mincho-bold.woff2?v={v['bold']}') format('woff2');font-weight:600 900;font-display:swap}}
@font-face{{font-family:'Akatsuki Mincho';src:url('akatsuki-mincho-extra-regular.woff2?v={v['extra-regular']}') format('woff2');font-weight:400 500;font-display:swap;unicode-range:{extra_range}}}
@font-face{{font-family:'Akatsuki Mincho';src:url('akatsuki-mincho-extra-bold.woff2?v={v['extra-bold']}') format('woff2');font-weight:600 900;font-display:swap;unicode-range:{extra_range}}}
@font-face{{font-family:'Akatsuki Cinzel';src:url('akatsuki-cinzel.woff2?v={v['cinzel']}') format('woff2');font-weight:400 900;font-display:swap}}
"""
(out / 'akatsuki-fonts.css').write_text(css, encoding='utf-8')
(out / 'glyphs.txt').write_text(''.join(sorted(c for c in core | extra if ord(c) >= 0x3000)), encoding='utf-8')
stamp = hashlib.sha1(css.encode()).hexdigest()[:8]
html = (root / 'akatsuki.html').read_text(encoding='utf-8')
html = re.sub(r'akatsuki-fonts/akatsuki-fonts\.css\?v=[0-9a-f]+', f'akatsuki-fonts/akatsuki-fonts.css?v={stamp}', html)
html = re.sub(r'akatsuki-fonts/akatsuki-mincho-regular\.woff2\?v=[0-9a-z]+', f"akatsuki-fonts/akatsuki-mincho-regular.woff2?v={v['regular']}", html)
(root / 'akatsuki.html').write_text(html, encoding='utf-8')
print('extra kanji', len(extra), '| css', stamp)
